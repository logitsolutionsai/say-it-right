"""How public sources say a name: keyless APIs, so the research step is quick and leaves a source behind.

    lookup("Christian Szegedy", context="computer scientist")

Returns candidates, never a verdict (which one wins is a judgement; see references/name-research.md):

- Wikipedia lead section: {{IPAc-en}} (rendered by Wikipedia itself, since its pieces are aliases: əːr is ɜːr),
  {{IPA|xx|...}}, the retired {{IPA-xx}}, {{respell}}, attached audio. Footnotes ({{efn}}) are included.
- Wikidata: IPA (P898) and pronunciation audio (P443, with the recording's language from P407) on the person and on
  their given/family-name items (P735/P734), where most Lingua Libre recordings of names live. People without an
  English article are found by a Wikidata search restricted to humans.
- Wiktionary: each word of the name; IPA generated by language modules ({{hu-IPA}}, {{es-pr}}) is expanded.
- Commons: audio files whose title carries the name (Lingua Libre "LL-Q..." and "Xx-Name.ogg" patterns).
- VOA Pronounce: Voice of America's newsmaker guide (respelling + audio).

Audio links are direct upload.wikimedia.org URLs with licence and author, so `vc.py hear <url>` can turn a
recording into IPA. Calls are spaced out, honour Retry-After on 429/503, and use a descriptive User-Agent with the
project's contact details, as Wikimedia's User-Agent policy asks (set VOICECHECK_CONTACT to give your own instead).
"""
from __future__ import annotations

import hashlib
import html
import json
import os
import re
import tempfile
import time
import unicodedata
import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path


def _ua() -> str:
    contact = os.environ.get("VOICECHECK_CONTACT", "https://github.com/logitsolutionsai/say-it-right; logitsolutionsai@gmail.com")
    from . import __version__
    return f"say-it-right/{__version__} (pronunciation lookup; {contact})"


_LAST = [0.0]


def _fetch(url: str, accept: str = "application/json", timeout: float = 20.0, tries: int = 3) -> bytes:
    for attempt in range(tries):
        wait = 0.25 - (time.time() - _LAST[0])             # be gentle with the public APIs
        if wait > 0:
            time.sleep(wait)
        req = urllib.request.Request(url, headers={"User-Agent": _ua(), "Accept": accept})
        try:
            with urllib.request.urlopen(req, timeout=timeout) as r:
                _LAST[0] = time.time()
                return r.read()
        except urllib.error.HTTPError as e:
            _LAST[0] = time.time()
            if e.code in (429, 503) and attempt < tries - 1:
                retry = e.headers.get("Retry-After", "")
                time.sleep(min(30.0, float(retry)) if retry.replace(".", "").isdigit() else 2.0 * (attempt + 1))
                continue
            raise
    raise RuntimeError("unreachable")


def _get(url: str, params: dict | None = None) -> dict:
    if params:
        url = url + "?" + urllib.parse.urlencode(params)
    return json.loads(_fetch(url).decode("utf-8"))


def _api(site: str, **params) -> dict:
    params.setdefault("format", "json")
    params.setdefault("formatversion", "2")
    return _get(f"https://{site}/w/api.php", params)


def _fold(s: str) -> str:
    """Case- and accent-insensitive form, which also maps Cyrillic look-alikes in Latin names (Wikidata's 'Iоffe')."""
    s = unicodedata.normalize("NFKD", s).translate(str.maketrans("аеорсухіјАЕОРСХІЈ", "aeopcyxijAEOPCXIJ"))
    return "".join(c for c in s if not unicodedata.combining(c)).casefold()


# ---------------------------------------------------------------- audio files

def commons_url(filename: str) -> str:
    """The direct upload.wikimedia.org URL of a Commons file (md5 path), so no redirect through commons.wikimedia.org,
    which some networks block."""
    name = unicodedata.normalize("NFC", filename.replace("File:", "").strip()).replace(" ", "_")
    name = name[0].upper() + name[1:] if name else name
    h = hashlib.md5(name.encode("utf-8")).hexdigest()
    return f"https://upload.wikimedia.org/wikipedia/commons/{h[0]}/{h[:2]}/{urllib.parse.quote(name)}"


def file_info(files: list[str]) -> dict[str, dict]:
    """URL, licence, author and length of Commons files, asked through en.wikipedia.org's shared file repository."""
    out = {}
    names = [f.replace("File:", "").strip() for f in files if f]
    for k in range(0, len(names), 20):
        chunk = names[k:k + 20]
        res = _api("en.wikipedia.org", action="query", titles="|".join("File:" + n for n in chunk), prop="imageinfo",
                   iiprop="url|mime|size|extmetadata", iiextmetadatafilter="LicenseShortName|Artist")
        for pg in res.get("query", {}).get("pages", []):
            info = (pg.get("imageinfo") or [{}])[0]
            if not info:
                continue
            meta = info.get("extmetadata", {})
            artist = re.sub(r"<[^>]+>", "", meta.get("Artist", {}).get("value", "")).strip()
            out[pg["title"].replace("File:", "").replace("_", " ")] = {
                "url": info.get("url"), "mime": info.get("mime"), "seconds": info.get("duration"),
                "license": meta.get("LicenseShortName", {}).get("value"), "author": artist or None}
    return out


def _audio(entries: list[dict]) -> list[dict]:
    """Fill in direct URLs, licences and authors for a list of {"file": ...} audio candidates."""
    if not entries:
        return entries
    try:
        info = file_info([e["file"] for e in entries])
    except Exception:
        info = {}
    for e in entries:
        key = e["file"].replace("File:", "").strip().replace("_", " ")
        key = key[:1].upper() + key[1:]                    # Commons capitalises the first letter
        meta = info.get(key) or {}
        e.update({"url": meta.get("url") or commons_url(key), "license": meta.get("license"),
                  "author": meta.get("author"), "seconds": meta.get("seconds")})
    return entries


def download(url: str) -> str:
    """Fetch an audio file (e.g. a Commons recording) to a temp file; returns its path."""
    if "commons.wikimedia.org/wiki/Special:FilePath/" in url:
        url = commons_url(urllib.parse.unquote(url.rsplit("/", 1)[1]))
    suffix = Path(urllib.parse.urlparse(url).path).suffix or ".audio"
    data = _fetch(url, accept="*/*", timeout=60)
    with tempfile.NamedTemporaryFile(suffix=suffix, delete=False) as f:
        f.write(data)
        return f.name


# ---------------------------------------------------------------- wikitext templates

_TPL = re.compile(r"\{\{\s*(IPA(?:-[a-z-]+)?|IPAc-[a-z]+|IPA-all|respell|[Aa]udio(?:-IPA)?|lang-[a-z-]+)\s*\|([^{}]*)\}\}")
_IPAC_LABELS = {"lang", "pron", "local", "ipa", "also", "uk", "us", "uklang", "uslang", "ukalso", "usalso", "alsouk",
                "alsous", "sometimes", "often", "usually", "canada", "australia", "nz", "-", "(", ")"}
# The commonest IPAc-en aliases (Module:IPAc-en/phonemes); lookup() asks Wikipedia to render the rest exactly.
_IPAC_ALIAS = {"əːr": "ɜːr", "ɝ": "ɜːr", "3r": "ɜːr", "3:r": "ɜːr", "A:": "ɑː", "@": "ə", "S": "ʃ", "sh": "ʃ",
               "Z": "ʒ", "zh": "ʒ", "T": "θ", "th": "θ", "D": "ð", "dh": "ð", "N": "ŋ", "ng": "ŋ", "tS": "tʃ",
               "ch": "tʃ", "dZ": "dʒ", "'": "ˈ", ",": "ˌ", "%": "ˌ", "i:": "iː", "u:": "uː", "O:": "ɔː", "eI": "eɪ",
               "aI": "aɪ", "oU": "oʊ", "aU": "aʊ", "OI": "ɔɪ", "I": "ɪ", "U": "ʊ", "E": "ɛ", "V": "ʌ", "{": "æ"}


def _ipac(pieces: list[str]) -> str:
    out = []
    for p in pieces:
        if p == "_":
            out.append(" ")
        elif p == ".":
            out.append(".")
        elif p.lower() not in _IPAC_LABELS:
            out.append(_IPAC_ALIAS.get(p, p))
    return re.sub(r"\s+", " ", "".join(out)).strip()


def templates(wikitext: str) -> dict:
    """Pronunciation templates in a stretch of wikitext: {'ipa': [{lang, ipa, template, raw}], 'respell': [...],
    'audio': [file names]}. Offline; `raw` is the template as written, for render()."""
    out = {"ipa": [], "respell": [], "audio": []}
    for m in _TPL.finditer(wikitext):
        name, body = m.group(1), m.group(2)
        args = [a.strip() for a in body.split("|")]
        named = dict(a.split("=", 1) for a in args if "=" in a)
        pos = [a for a in args if "=" not in a]
        for k in ("audio", "file"):
            if named.get(k):
                out["audio"].append(named[k].strip())
        low = name.lower()
        if low.startswith("audio"):
            if pos:
                out["audio"].append(pos[0])
        elif low == "respell":                             # {{respell|SUR|shə|_|OO|nə}}: _ is a space
            out["respell"].append(re.sub(r"\s*-?_-?\s*", " ", "-".join(p for p in pos if p)).strip())
        elif low == "ipac-en":                             # other IPAc-xx templates take spelling, not IPA
            ipa = _ipac([p for p in pos if p])
            if ipa:
                out["ipa"].append({"lang": "en", "ipa": ipa, "template": "IPAc-en", "raw": m.group(0)})
        elif low == "ipa" and len(pos) >= 2:               # {{IPA|hu|ˈsɛɡɛdi|lang|audio}}
            out["ipa"].append({"lang": pos[0], "ipa": pos[1], "template": "IPA", "raw": m.group(0)})
            if len(pos) >= 4 and re.search(r"\.(ogg|oga|wav|mp3|flac|opus)$", pos[3], re.I):
                out["audio"].append(pos[3])
        elif low.startswith("ipa-") and pos and low != "ipa-all":   # {{IPA-hu|...}}: retired, still in old text
            out["ipa"].append({"lang": low[4:], "ipa": pos[0], "template": name, "raw": m.group(0)})
        elif low.startswith("lang-") and named.get("p"):   # {{lang-rus|Ио́ффе|p=ɪˈofɛ}}
            out["ipa"].append({"lang": low[5:], "ipa": named["p"], "template": name, "raw": m.group(0)})
    for k in out:
        seen, keep = set(), []
        for x in out[k]:
            key = json.dumps({a: b for a, b in x.items() if a != "raw"} if isinstance(x, dict) else x,
                             sort_keys=True, ensure_ascii=False)
            if key not in seen:
                seen.add(key)
                keep.append(x)
        out[k] = keep
    return out


_IPA_CHARS = set("ˈˌːəɪʊɛɔæɑɒʌɜɐɚɝθðʃʒŋɡɹɾʁʀχɣɲʎøœɨʉɯɤɵɘʏçʝɕʑʂʐɖʈɳɭɻɬɮʔʕħβɸʋɥ")


def render(site: str, title: str, wikitext: str) -> list[str]:
    """The IPA a template renders to, as the wiki itself writes it (resolves IPAc-en aliases, Wiktionary's
    language modules). The template is parsed to HTML, the tags dropped (IPAc-en nests a span per phoneme), and
    each /.../ or [...] read off the text."""
    res = _api(site, action="parse", title=title, text=wikitext, prop="text", contentmodel="wikitext",
               disablelimitreport=1)
    htm = res.get("parse", {}).get("text", "")
    htm = re.sub(r"<(sup|style|script)[^>]*>.*?</\1>", "", htm, flags=re.S)
    text = html.unescape(re.sub(r"<[^>]+>", "", htm))
    out = []
    for m in re.finditer(r"/([^/\n]{1,80})/|\[([^\]\n]{1,80})\]", text):
        ipa = (m.group(1) or m.group(2)).strip()
        if ipa and set(ipa) & _IPA_CHARS and not ipa.startswith(("http", "edit")):
            out.append(ipa)
    return list(dict.fromkeys(out))


# ---------------------------------------------------------------- sources

def _words(s: str) -> list[str]:
    return re.findall(r"[^\W\d_][\w'-]*", s)


def _about(title: str, name: str, person: bool = True) -> bool:
    """Is a search hit about `name`? person=True: the title carries every word of the name ("Sergey Ioffe" is not
    "Abram Ioffe"); person=False: just the surname, for related pages that show how the surname is said."""
    words = [_fold(w) for w in _words(name)]
    have = set(_fold(w) for w in _words(title))
    if not words:
        return False
    return all(w in have for w in words) if person else words[-1] in have


def wikipedia(name: str, lang: str = "en", context: str | None = None, limit: int = 5) -> list[dict]:
    site = f"{lang}.wikipedia.org"
    titles = []
    exact = _api(site, action="query", titles=name, redirects=1)
    for pg in exact.get("query", {}).get("pages", []):
        if not pg.get("missing") and "title" in pg:
            titles.append(pg["title"])
    hits = _api(site, action="query", list="search", srsearch=f"{name} {context or ''}".strip(), srlimit=limit)
    found_titles = [h["title"] for h in hits.get("query", {}).get("search", [])]
    titles += [t for t in found_titles if _about(t, name)]
    related = [t for t in found_titles if t not in titles and _about(t, name, person=False)]
    out = []
    for title in (list(dict.fromkeys(titles))[:3] + related[:2]):
        page = _api(site, action="parse", page=title, prop="wikitext", section=0, redirects=1)
        text = page.get("parse", {}).get("wikitext", "")
        props = _api(site, action="query", prop="pageprops", titles=title, ppprop="wikibase_item", redirects=1)
        qid = next((p.get("pageprops", {}).get("wikibase_item") for p in props.get("query", {}).get("pages", [])),
                   None)
        found = templates(text)
        for x in found["ipa"]:
            if x["template"] == "IPAc-en":                 # let Wikipedia resolve the aliases
                try:
                    rendered = [r for r in render(site, title, x["raw"]) if not r.startswith("Help:")]
                    if rendered:
                        x["ipa"] = rendered[0]
                except Exception:
                    pass
            x.pop("raw", None)
        out.append({"title": title, "url": f"https://{site}/wiki/{urllib.parse.quote(title.replace(' ', '_'))}",
                    "match": "person" if title not in related else "surname only (a related page, not this person)",
                    "wikidata": qid, "ipa": found["ipa"], "respell": found["respell"],
                    "audio": _audio([{"file": a} for a in found["audio"]])})
    return out


def _claims(entity: dict, prop: str) -> list[dict]:
    out = []
    for c in entity.get("claims", {}).get(prop, []):
        val = c.get("mainsnak", {}).get("datavalue", {}).get("value")
        if val is None:
            continue
        langs = [q.get("datavalue", {}).get("value", {}).get("id") for q in c.get("qualifiers", {}).get("P407", [])]
        out.append({"value": val, "language": [x for x in langs if x]})
    return out


def _entity(qid: str) -> dict:
    return _get("https://www.wikidata.org/wiki/Special:EntityData/" + qid + ".json")["entities"][qid]


def _label(e: dict) -> str | None:
    labels = e.get("labels", {})
    return (labels.get("en") or labels.get("mul") or next(iter(labels.values()), {})).get("value")


def wikidata(qid: str, follow_names: bool = True, only_names: str | None = None) -> dict:
    """IPA (P898) and pronunciation audio (P443) on an item, and on its given/family-name items (P735, P734);
    with `only_names`, just the name items whose label appears in it (not LeCun's second given name André)."""
    ent = _entity(qid)
    res = {"qid": qid, "label": _label(ent), "ipa": [], "audio": [], "names": []}

    def collect(e, on):
        for c in _claims(e, "P898"):
            v = c["value"]
            res["ipa"].append({"ipa": v if isinstance(v, str) else v.get("text"), "language": c["language"], "on": on})
        for c in _claims(e, "P443"):
            res["audio"].append({"file": c["value"], "language": c["language"], "on": on})
    collect(ent, "person")
    if follow_names:
        for prop, role in (("P735", "given name"), ("P734", "family name")):
            for c in _claims(ent, prop):
                nid = c["value"].get("id") if isinstance(c["value"], dict) else None
                if not nid:
                    continue
                ne = _entity(nid)
                nlabel = _label(ne)
                if only_names and (not nlabel or _fold(nlabel) not in _fold(only_names)):
                    continue
                res["names"].append({"qid": nid, "label": nlabel, "role": role})
                collect(ne, f"{role} {nlabel}")
    langs = {q for x in res["audio"] + res["ipa"] for q in x["language"]}
    if langs:                                              # Q1860 -> English, Q9067 -> Hungarian...
        lab = _get("https://www.wikidata.org/w/api.php", {"action": "wbgetentities", "ids": "|".join(sorted(langs)),
                                                           "props": "labels", "languages": "en", "format": "json"})
        names = {k: v.get("labels", {}).get("en", {}).get("value", k) for k, v in lab.get("entities", {}).items()}
        for x in res["audio"] + res["ipa"]:
            x["language"] = [names.get(q, q) for q in x["language"]]
    _audio(res["audio"])
    return res


def wikidata_person(name: str) -> str | None:
    """The Wikidata item of a person with no English article: a search restricted to humans (P31=Q5)."""
    res = _api("www.wikidata.org", action="query", list="search", srsearch=f"{name} haswbstatement:P31=Q5", srlimit=5)
    for hit in res.get("query", {}).get("search", []):
        ent = _entity(hit["title"])
        if _about(_label(ent) or "", name):
            return hit["title"]
    return None


def name_items(word: str) -> list[dict]:
    """Wikidata given/family-name items for `word` that carry IPA or recordings."""
    res = _get("https://www.wikidata.org/w/api.php", {"action": "wbsearchentities", "search": word, "language": "en",
                                                       "type": "item", "limit": 10, "format": "json"})
    out = []
    for hit in res.get("search", []):
        desc = (hit.get("description") or "").lower()
        if _fold(hit.get("label", "")) == _fold(word) and ("name" in desc or "surname" in desc):
            d = wikidata(hit["id"], follow_names=False)
            d["description"] = hit.get("description")
            if d["ipa"] or d["audio"]:
                out.append(d)
    return out


_WIKT_MODULE = re.compile(r"\{\{\s*([a-z]{2,3}(?:-[a-z]+)?)-(?:IPA|pr|ipa|pron)\s*(?:\|[^{}]*)?\}\}")


def wiktionary(word: str, lang: str = "en") -> dict | None:
    site = f"{lang}.wiktionary.org"
    try:
        page = _api(site, action="parse", page=word, prop="wikitext", redirects=1)
    except Exception:
        return None
    text = page.get("parse", {}).get("wikitext", "")
    if not text:
        return None
    sections = re.split(r"\n==([^=].*?)==\n", "\n" + text)     # level-2 headers are languages on en.wiktionary
    found = []
    for k in range(1, len(sections) - 1, 2):
        langname, body = sections[k].strip(), sections[k + 1]
        for line in re.findall(r"\{\{IPA\|[a-z-]+\|([^}]*)\}\}", body):
            for piece in line.split("|"):
                if piece.startswith(("/", "[")):
                    found.append({"language": langname, "ipa": piece.strip("/[]")})
        for m in _WIKT_MODULE.finditer(body):                    # {{hu-IPA}}, {{es-pr|+}}: generated, expand them
            try:
                for ipa in render(site, word, m.group(0)):
                    found.append({"language": langname, "ipa": ipa, "template": m.group(1) + "-IPA"})
            except Exception:
                pass
        for a in re.findall(r"\{\{audio\|[a-z-]+\|([^|}]+)", body):
            found.append({"language": langname, "file": a.strip()})
    audio = _audio([x for x in found if "file" in x])
    uniq = list({json.dumps(x, sort_keys=True, ensure_ascii=False): x for x in found if "ipa" in x}.values())
    if not uniq and not audio:
        return None
    return {"word": word, "url": f"https://{site}/wiki/{urllib.parse.quote(word)}", "pronunciations": uniq,
            "audio": audio}


_NAME_FILE = re.compile(r"^(?:LL-Q\d+ \([a-z]{3}\)-.+|[A-Z][a-z]{1,2}(?:-[a-z]{2})?-.+)\.(?:wav|ogg|oga|mp3|flac|opus)$")


def commons_audio(word: str, limit: int = 10) -> list[dict]:
    """Pronunciation recordings on Commons whose title carries `word` (Lingua Libre and "Xx-Word.ogg" files)."""
    q = f"intitle:{word} filetype:audio"
    keys: list[str] = []
    try:
        res = _api("commons.wikimedia.org", action="query", list="search", srnamespace=6, srsearch=q, srlimit=limit)
        keys = [h["title"] for h in res.get("query", {}).get("search", [])]
    except Exception:                                      # commons.wikimedia.org is blocked on some networks
        try:
            res = _get("https://api.wikimedia.org/core/v1/commons/search/page", {"q": f"file:{q}", "limit": limit})
            keys = [p["key"] for p in res.get("pages", [])]
        except Exception:
            return []
    files = [k.replace("File:", "").replace("_", " ") for k in keys]
    return _audio([{"file": f} for f in files if records(f, word)])


def records(filename: str, word: str) -> bool:
    """Is this Commons file a recording of `word` (alone, or ending a full name)? "En-us-Joaquin.oga",
    "LL-Q9142 (gle)-Wikiroisin-saoirse.wav", "LL-Q150 (fra)-X-Emmanuel Macron.wav" are; "En-us-anti-Christian.ogg"
    and "De-Christian Wolfgang Lindner.ogg" are not."""
    if not _NAME_FILE.match(filename):
        return False
    stem, w = _fold(filename.rsplit(".", 1)[0]), _fold(word)
    if stem.startswith("ll-q"):                            # LL-Q<lang> (<code>)-<speaker, may hold hyphens>-<word>
        return stem.endswith("-" + w) or stem.endswith(" " + w)
    said = re.sub(r"^[a-z]{2,3}(?:-[a-z]{2})?-", "", stem)  # Xx-word, Xx-yy-word
    return said == w or said.endswith(" " + w)


def voa(name: str) -> list[dict]:
    """Voice of America's pronunciation guide (newsmakers; ~7,000 names): respelling and audio."""
    last = re.findall(r"[^\W\d_][\w'-]*", name)
    if not last:
        return []
    raw = _fetch("https://pronounce.voanews.com/searchresults.php?" + urllib.parse.urlencode({"keywords": last[-1]}),
                 accept="text/html").decode("utf-8", "replace")
    out = []
    for m in re.finditer(r'href="(/sounds/[^"]+)"\s+title="([^"]+)".*?<td>\s*(?:<strong>)?[^<]*(?:</strong>)?\s*</td>'
                         r'\s*<td>([^<]*)</td>', raw, re.S):
        who = html.unescape(m.group(2))
        if all(_fold(w) in _fold(who) for w in last):
            out.append({"name": who, "respell": html.unescape(m.group(3)).strip(),
                        "audio": "https://pronounce.voanews.com" + m.group(1)})
    return out


def lookup(name: str, lang: str = "en", context: str | None = None) -> dict:
    """Every candidate pronunciation the keyless sources have for `name`, with where each came from."""
    out = {"query": name, "wikipedia": [], "wikidata": [], "wiktionary": [], "commons": [], "voa": [], "errors": []}

    def attempt(label, fn):
        try:
            return fn()
        except Exception as e:
            out["errors"].append(f"{label}: {type(e).__name__}: {e}")
            return None
    out["wikipedia"] = attempt("wikipedia", lambda: wikipedia(name, lang, context)) or []
    qid = next((p["wikidata"] for p in out["wikipedia"] if p.get("wikidata") and p["match"] == "person"), None)
    if not qid:
        qid = attempt("wikidata search", lambda: wikidata_person(name))
    if qid:
        d = attempt("wikidata", lambda: wikidata(qid, only_names=name))
        if d:
            out["wikidata"].append(d)
    words = list(dict.fromkeys(re.findall(r"[^\W\d_][\w'-]*", name)))
    covered = {_fold(n["label"] or "") for d in out["wikidata"] for n in d.get("names", [])}
    for word in words:
        if _fold(word) not in covered:                     # the name's own items, when the person didn't link them
            out["wikidata"] += attempt(f"wikidata {word}", lambda w=word: name_items(w)) or []
        w = attempt(f"wiktionary {word}", lambda w=word: wiktionary(w, lang))
        if w:
            out["wiktionary"].append(w)
        out["commons"] += attempt(f"commons {word}", lambda w=word: commons_audio(w)) or []
    out["voa"] = attempt("voa", lambda: voa(name)) or []
    return out
